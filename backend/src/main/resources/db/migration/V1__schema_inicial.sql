-- Schema do MVP (N1): usuarios, livros e transacoes de credito.
-- Bancos criados antes do Flyway pelo ddl-auto=update entram por baseline nesta versao
-- (spring.flyway.baseline-on-migrate) e nao executam este script.

CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    email          VARCHAR(255) NOT NULL,
    senha_hash     VARCHAR(255) NOT NULL,
    saldo_creditos INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    -- RN critica: o saldo nunca fica negativo, nem por falha na aplicacao.
    CONSTRAINT ck_usuarios_saldo_nao_negativo CHECK (saldo_creditos >= 0)
);

CREATE TABLE livros (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo               VARCHAR(255) NOT NULL,
    autor                VARCHAR(255) NOT NULL,
    genero               VARCHAR(255) NOT NULL,
    status               VARCHAR(255) NOT NULL,
    id_usuario_doador    BIGINT       NOT NULL,
    id_usuario_recebedor BIGINT,
    CONSTRAINT ck_livros_status CHECK (status IN ('DISPONIVEL', 'RESGATADO')),
    CONSTRAINT fk_livros_doador FOREIGN KEY (id_usuario_doador) REFERENCES usuarios (id),
    CONSTRAINT fk_livros_recebedor FOREIGN KEY (id_usuario_recebedor) REFERENCES usuarios (id)
);

CREATE TABLE transacoes_credito (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT       NOT NULL,
    tipo       VARCHAR(255) NOT NULL,
    descricao  VARCHAR(255) NOT NULL,
    criado_em  TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_transacoes_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT fk_transacoes_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id)
);
